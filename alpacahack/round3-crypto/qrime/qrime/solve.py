# compute r_next
r_next = r+1
while not isPrime(r_next):
    r_next += 1
S = r + r_next

# search small g
q = None
for g in range(1, 20000):
    D = g*g*r*r + 4*S*n
    sqrtD = math.isqrt(D)
    if sqrtD*sqrtD != D:
        continue
    num = -g*r + sqrtD
    den = 2*S
    if num % den != 0:
        continue
    q_candidate = num // den
    if q_candidate > 0 and n % q_candidate == 0:
        q = q_candidate
        break

p = n // q
phi = (p-1)*(q-1)
d = inverse(e, phi)

# Fully automated solver using pwntools and SageMath.
# This version is self-contained and does NOT require the 'untwister' tool.
#
# Run this script using the SageMath python interpreter:
#    $ sage -python solve.py

from pwn import *
from Crypto.Util.number import long_to_bytes, bytes_to_long
import random

# --- SageMath Imports ---
# These will only work when run with `sage -python`
from sage.all import IntegerModRing, PolynomialRing, Matrix, GF, vector, Integers

# --- Mersenne Twister Recovery Logic (Alternative to 'untwister') ---

def temper(y):
    """The tempering function of MT19937."""
    y ^= (y >> 11)
    y ^= (y << 7) & 0x9d2c5680
    y ^= (y << 15) & 0xefc60000
    y ^= (y >> 18)
    return y

def recover_mt_state(bits):
    """
    Recovers the internal state of Python's random module (MT19937)
    from 19968 consecutive LSBs of its output.
    This uses SageMath's linear algebra over GF(2).
    """
    log.info("Starting MT19937 state recovery from LSBs...")
    N = 624
    W = 32
    M_param = 397
    A = 0x9908b0df
    UPPER_MASK = 0x80000000
    LOWER_MASK = 0x7fffffff
    
    assert len(bits) == N * W
    
    observed_bits = vector(GF(2), [int(b) for b in bits])
    
    # Matrix to map state bits to output LSBs
    M = Matrix(GF(2), N * W)
    
    # This loop constructs the matrix column by column
    for i in range(N * W):
        # Create a state basis vector (only the i-th bit is 1)
        state = [0] * N
        state[i // W] = 1 << (i % W)
        
        # Simulate the generator's output based on this single bit
        # The generator produces outputs in blocks of N
        
        # First block of N outputs is from the initial state
        for j in range(N):
            y = temper(state[j])
            M[j, i] = y & 1
            
        # Subsequent blocks are generated by twisting the previous state
        for block_start in range(N, N * W, N):
            # Perform the twist operation to generate the next N state words
            for k in range(N):
                y = (state[k] & UPPER_MASK) | (state[(k + 1) % N] & LOWER_MASK)
                next_val = state[(k + M_param) % N] ^ (y >> 1)
                if y & 1:
                    next_val ^= A
                state[k] = next_val

            # The next N outputs are from this newly twisted state
            for k in range(N):
                if block_start + k < N * W:
                    y = temper(state[k])
                    M[block_start + k, i] = y & 1

    log.info("Matrix constructed. Solving for the original state...")
    original_state_bits = M.solve_right(observed_bits)
    
    # Reconstruct the state integers from the bit vector
    state_ints = []
    for i in range(N):
        val = 0
        for j in range(W):
            if original_state_bits[i * W + j]:
                val |= (1 << j)
        state_ints.append(val)
        
    log.success("Successfully recovered MT19937 state.")
    return tuple([3, tuple(state_ints) + (0,), None])


def solve():
    # --- STEP 1: Connect and gather data ---
    HOST = "ctf.compfest.id"
    PORT = 7101
    
    io = remote(HOST, PORT)
    
    log.info("Receiving 19968 odd/even bits...")
    bits = ""
    for _ in range(19968):
        line = io.recvline().decode().strip()
        if line == "even":
            bits += "0"
        else:
            bits += "1"
    
    log.success("Finished receiving bits.")
    
    # --- STEP 2: Parse crypto parameters from server ---
    log.info("Parsing cryptographic parameters...")
    p = int(io.recvline().decode().split("=")[1])
    e = int(io.recvline().decode().split("=")[1])
    n = int(io.recvline().decode().split("=")[1])
    coeffs = eval(io.recvline().decode().split("=")[1])
    c1_test_noisy = int(io.recvline().decode().split("=")[1])
    c2_test_noisy = int(io.recvline().decode().split("=")[1])
    c1_secret_noisy = int(io.recvline().decode().split("=")[1])
    c2_secret_noisy = int(io.recvline().decode().split("=")[1])
    log.success("Parameters parsed.")
    print(f"p = {p}")
    print(f"n = {n}")

    # --- STEP 3: Recover noise using internal logic ---
    recovered_state = recover_mt_state(bits)
    
    # Create a new random generator and set its state to the recovered one
    predictor = random.Random()
    predictor.setstate(recovered_state)
    
    # Predict the next four 1024-bit noise values
    noise1 = predictor.getrandbits(1024)
    noise2 = predictor.getrandbits(1024)
    noise3 = predictor.getrandbits(1024)
    noise4 = predictor.getrandbits(1024)
    log.success("Successfully predicted 4 noise values.")

    # --- STEP 4: The Decryption Logic ---
    log.info("Starting decryption...")
    
    c2_test = c2_test_noisy - noise2
    c2_secret = c2_secret_noisy - noise4

    test_msg = bytes_to_long(b"This is just a test message.")
    Zn = IntegerModRing(n)

    s = Zn(c2_test) * Zn(test_msg)**-1
    log.info(f"Recovered shared secret s.")

    poly_result = Zn(c2_secret) * s**-1
    log.info(f"Recovered poly_result.")

    # --- STEP 5: Solve for the flag using Hensel's Lemma ---
    log.info("Solving polynomial for the flag using Hensel's Lemma...")

    # Define the polynomial ring over the Integers for lifting
    P_int = PolynomialRing(Integers(), 'm_int')
    m_int = P_int.gen()
    f_int = 0
    for i in range(e):
        f_int += coeffs[i] * m_int**i
    f_int -= int(poly_result)

    # 1. Solve the polynomial modulo p
    Zp = GF(p)
    P_p = PolynomialRing(Zp, 'm_p')
    m_p = P_p.gen()
    f_p = P_p(f_int)
    roots_p = f_p.roots(multiplicities=False)
    log.info(f"Found {len(roots_p)} root(s) modulo p: {roots_p}")

    if not roots_p:
        log.failure("No roots found modulo p. Cannot proceed.")
        io.close()
        return

    # 2. Lift each root from mod p up to mod p^100
    f_prime = f_int.derivative()

    for r0 in roots_p:
        r = int(r0)
        mod = p
        
        f_prime_val_mod_p = Zp(f_prime(r))
        if f_prime_val_mod_p == 0:
            log.warning(f"Derivative is zero for root {r} mod p. Lifting might be ambiguous. Skipping.")
            continue
            
        f_prime_inv = f_prime_val_mod_p**-1

        for _ in range(1, 100): # k=100, so we lift 99 times
            f_val = f_int(r)
            t = - (f_val // mod) * f_prime_inv
            t = int(t) # Get the integer value in the correct range
            
            r = r + t * mod
            mod *= p

        # After lifting, r is the root mod p^100 = n
        m_solution = r
        
        # Verify the solution and check if it's a printable flag
        if f_int(m_solution) % n == 0:
            flag = long_to_bytes(m_solution)
            try:
                decoded_flag = flag.decode()
                log.success(f"Successfully lifted root: {m_solution}")
                log.success(f"FLAG: {decoded_flag}")
                print("\n" + "="*20)
                print(f"  FLAG: {decoded_flag}")
                print("="*20 + "\n")
                io.close()
                return # Exit after finding the flag
            except UnicodeDecodeError:
                log.warning(f"Lifted root {m_solution} but it's not a valid UTF-8 string. Trying next root.")
                log.warning(f"Bytes (hex): {flag.hex()}") # ADDED FOR DEBUGGING
                continue # This root is mathematically correct but not the flag

    log.failure("Hensel's Lemma failed to find a valid root for any initial solution.")
    io.close()

if __name__ == "__main__":
    solve()
